for loc in locales:
    # Update common.json: nav.backups and common.loading
    common_path = f'{base}/{loc}/common.json'
    with open(common_path, 'rb') as f:
        raw = f.read()
    text = raw.decode('utf-8')
    import re
    data = json.loads(text)
    common = data.setdefault('common', {})
    nav = data.setdefault('nav', {})
    if COMMON_FIX[loc].get('nav.backups') and 'backups' not in nav:
        # Insert nav.backups in the right place (after 'archives' / before 'stacks' or similar)
        # Use a simple append at the end of nav, which is conventional
        nav['backups'] = COMMON_FIX[loc]['nav.backups']
    common_loading = COMMON_FIX[loc].get('common.loading')
    if common_loading and 'loading' not in common:
        common['loading'] = common_loading
    text = json.dumps(data, ensure_ascii=False, indent=2) + '\n'
    with open(common_path, 'wb') as f:
        f.write(text.encode('utf-8'))
    print(f'{loc}/common.json updated')

    # Update containers.json: add the missing backups tab/log keys
    cont_path = f'{base}/{loc}/containers.json'
    with open(cont_path, 'rb') as f:
        raw = f.read()
    text = raw.decode('utf-8')
    data = json.loads(text)
    bk = data.setdefault('backups', {})
    keys_added = 0
    for k, v in BACKUPS_TAB_AND_LOGS_FIX[loc].items():
        # If the key has a dot (like 'logs.title'), we need a nested object
        if '.' in k:
            top, sub = k.split('.', 1)
            target = bk.setdefault(top, {})
            if sub not in target:
                target[sub] = v
                keys_added += 1
        else:
            if k not in bk:
                bk[k] = v
                keys_added += 1
    text = json.dumps(data, ensure_ascii=False, indent=2) + '\n'
    with open(cont_path, 'wb') as f:
        f.write(text.encode('utf-8'))
    print(f'{loc}/containers.json updated ({keys_added} new keys)')
