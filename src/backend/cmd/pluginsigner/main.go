// Command pluginsigner signs the first-party plugin tarballs produced
// during the image build and records each signature in the catalog
// entry that points at it.
//
// It runs inside the builder stage because the tarballs are created
// there: gzip output is not reproducible, so a signature computed
// anywhere else would be a signature of different bytes. The private
// key arrives as a BuildKit secret mount and never becomes a layer.
//
// Signature format matches src/plugins/scripts/sign-plugin.py and what
// the installer verifies: raw ed25519 over the whole tarball, written
// base64 into the catalog entry's "signature" field and alongside the
// archive as <tarball>.sig.
//
// Widget catalog entries (-widget) are signed differently: over the widgetsig
// manifest (key, version, bundle sha256, metadata sha256), written into the entry's
// "signature" and "sha256" fields, because a bundle-only signature let a signed
// bundle be re-listed under another key, version or label.
//
// A missing key file is not an error. An operator building McHarbor
// without the release key must still get a working image — they get an
// unsigned one, which the store labels honestly.
package main

import (
	"crypto/ed25519"
	"crypto/rand"
	"crypto/x509"
	"encoding/base64"
	"encoding/json"
	"encoding/pem"
	"errors"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"

	"github.com/therealmcsparrow/mcharbor/core/plugin/host"
	"github.com/therealmcsparrow/mcharbor/core/widgetsig"
)

func main() {
	dir := flag.String("dir", "", "directory holding the catalog JSON files and their tarballs")
	keyPath := flag.String("key", "", "ed25519 private key: 32-byte seed or 64-byte expanded key")
	trustPath := flag.String("trust", "", "ed25519 public key: verify each signature after writing it")
	keygen := flag.String("keygen", "", "write a new key pair to <prefix>.key (32-byte seed) and <prefix>.pub (PEM) and exit")
	filePath := flag.String("file", "", "sign this one file (e.g. an agent release SHA256SUMS) into <file>.sig instead of a catalog directory")
	widgetPath := flag.String("widget", "", "sign widget catalog entries (one <key>.json or a widgets/ directory) over the widget manifest")
	flag.Parse()

	if *keygen != "" {
		if err := generateKeyPair(*keygen); err != nil {
			log.Fatalf("pluginsigner: %v", err)
		}
		fmt.Printf("pluginsigner: wrote %s.key and %s.pub\n", *keygen, *keygen)
		return
	}
	if *filePath != "" {
		if err := signOneFile(*filePath, *keyPath, *trustPath); err != nil {
			log.Fatalf("pluginsigner: %v", err)
		}
		return
	}
	if *widgetPath != "" {
		if err := signWidgets(*widgetPath, *keyPath, *trustPath); err != nil {
			log.Fatalf("pluginsigner: %v", err)
		}
		return
	}

	if *dir == "" || *keyPath == "" {
		log.Fatal("pluginsigner: both -dir and -key are required")
	}

	key, err := loadKey(*keyPath)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			fmt.Printf("pluginsigner: no signing key at %s — leaving plugins unsigned\n", *keyPath)
			return
		}
		log.Fatalf("pluginsigner: %v", err)
	}

	sigs, err := signTarballs(*dir, key)
	if err != nil {
		log.Fatalf("pluginsigner: %v", err)
	}
	if *trustPath != "" {
		if err := verifySignatures(*dir, sigs, *trustPath); err != nil {
			log.Fatalf("pluginsigner: %v", err)
		}
		fmt.Printf("pluginsigner: verified %d signature(s) against %s\n", len(sigs), *trustPath)
	}
	patched, err := patchCatalogs(*dir, sigs)
	if err != nil {
		log.Fatalf("pluginsigner: %v", err)
	}
	fmt.Printf("pluginsigner: signed %d tarballs, recorded %d catalog signatures\n", len(sigs), patched)
}

// loadKey accepts either the 32-byte seed PyNaCl writes or a full
// 64-byte ed25519 private key, so a key generated by either tool works.
func loadKey(path string) (ed25519.PrivateKey, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	raw = trimKeyBytes(raw)
	switch len(raw) {
	case ed25519.SeedSize:
		return ed25519.NewKeyFromSeed(raw), nil
	case ed25519.PrivateKeySize:
		return ed25519.PrivateKey(raw), nil
	default:
		return nil, fmt.Errorf("key %s is %d bytes, want %d (seed) or %d (expanded)",
			path, len(raw), ed25519.SeedSize, ed25519.PrivateKeySize)
	}
}

// trimKeyBytes strips trailing whitespace a text editor may have added
// without touching the key material itself.
func trimKeyBytes(b []byte) []byte {
	return []byte(strings.TrimRight(string(b), "\r\n\t "))
}

// verifySignatures re-reads each tarball and checks the signature just written
// against the trust key the host will actually verify with.
//
// A signature the host cannot verify is worse than none: the install succeeds,
// logs "installing unsigned plugin", and the mismatch shows up only in a line
// nobody reads. Signing with the wrong key is the easy way to get there, so the
// check belongs in the same run rather than in a later one nobody makes.
func verifySignatures(dir string, sigs map[string]string, trustPath string) error {
	keys, err := loadTrustKeys(trustPath)
	if err != nil {
		return err
	}

	for name, encoded := range sigs {
		sig, err := base64.StdEncoding.DecodeString(encoded)
		if err != nil {
			return fmt.Errorf("decoding signature for %s: %w", name, err)
		}
		payload, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return fmt.Errorf("reading %s: %w", name, err)
		}
		if !verifiesWithAny(keys, payload, sig) {
			return fmt.Errorf("signature for %s does not verify against %s - the host would treat this plugin as unsigned", name, trustPath)
		}
	}
	return nil
}

// verifiesWithAny reports whether any of keys verifies sig over payload.
func verifiesWithAny(keys []ed25519.PublicKey, payload, sig []byte) bool {
	for _, pub := range keys {
		if ed25519.Verify(pub, payload, sig) {
			return true
		}
	}
	return false
}

// loadTrustKeys reads the trust key file the host will verify with.
func loadTrustKeys(trustPath string) ([]ed25519.PublicKey, error) {
	raw, err := os.ReadFile(trustPath)
	if err != nil {
		return nil, fmt.Errorf("reading trust key %s: %w", trustPath, err)
	}

	// The host's own parser, not a second one: this check is only worth
	// anything if it accepts exactly what the installer will accept. The key
	// on disk is PEM (PKIX or RFC 8410); a bare 32-byte file is tolerated
	// because the private half is stored that way.
	keys, err := host.ParsePEMPublicKeys(raw)
	if err != nil {
		return nil, fmt.Errorf("parsing trust key %s: %w", trustPath, err)
	}
	if len(keys) == 0 {
		trimmed := trimKeyBytes(raw)
		if len(trimmed) != ed25519.PublicKeySize {
			return nil, fmt.Errorf("trust key %s holds no usable ed25519 public key", trustPath)
		}
		keys = []ed25519.PublicKey{ed25519.PublicKey(trimmed)}
	}
	return keys, nil
}

// signTarballs signs every .tar.gz in dir and returns base64 signatures
// keyed by file name.
func signTarballs(dir string, key ed25519.PrivateKey) (map[string]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("reading %s: %w", dir, err)
	}
	out := make(map[string]string, len(entries))
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".tar.gz") {
			continue
		}
		path := filepath.Join(dir, name)
		payload, err := os.ReadFile(path)
		if err != nil {
			return nil, fmt.Errorf("reading %s: %w", path, err)
		}
		sig := base64.StdEncoding.EncodeToString(ed25519.Sign(key, payload))
		if err := os.WriteFile(path+".sig", []byte(sig), 0o644); err != nil {
			return nil, fmt.Errorf("writing %s.sig: %w", path, err)
		}
		out[name] = sig
	}
	return out, nil
}

// patchCatalogs writes each signature into the catalog entry whose
// download_url names that tarball. Entries whose archive is absent are
// left alone rather than guessed at — a signature on the wrong bytes is
// worse than no signature, because it would fail verification at
// install time with no way to tell why.
func patchCatalogs(dir string, sigs map[string]string) (int, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return 0, fmt.Errorf("reading %s: %w", dir, err)
	}
	count := 0
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".json") {
			continue
		}
		path := filepath.Join(dir, e.Name())
		raw, err := os.ReadFile(path)
		if err != nil {
			return 0, fmt.Errorf("reading %s: %w", path, err)
		}
		var doc map[string]any
		if err := json.Unmarshal(raw, &doc); err != nil {
			// A catalog file this tool cannot parse is the catalog
			// loader's problem to report, not a reason to fail the build.
			fmt.Printf("pluginsigner: skipping unparsable %s: %v\n", e.Name(), err)
			continue
		}
		changed := applySignatures(doc, sigs, &count)
		if !changed {
			continue
		}
		out, err := json.MarshalIndent(doc, "", "  ")
		if err != nil {
			return 0, fmt.Errorf("encoding %s: %w", path, err)
		}
		if err := os.WriteFile(path, append(out, '\n'), 0o644); err != nil {
			return 0, fmt.Errorf("writing %s: %w", path, err)
		}
	}
	return count, nil
}

// applySignatures stamps every version entry that has a matching
// tarball, plus the top-level mirror of versions[0] the catalog model
// keeps for legacy single-version consumers.
func applySignatures(doc map[string]any, sigs map[string]string, count *int) bool {
	changed := false
	versions, _ := doc["versions"].([]any)
	for i, v := range versions {
		entry, ok := v.(map[string]any)
		if !ok {
			continue
		}
		url, _ := entry["download_url"].(string)
		sig, ok := sigs[filepath.Base(url)]
		if !ok {
			continue
		}
		entry["signature"] = sig
		changed = true
		*count++
		if i == 0 {
			doc["signature"] = sig
		}
	}
	// Entries written in the flat single-version shape carry the URL at
	// the top level instead of in a versions array.
	if !changed {
		if url, ok := doc["download_url"].(string); ok {
			if sig, ok := sigs[filepath.Base(url)]; ok {
				doc["signature"] = sig
				changed = true
				*count++
			}
		}
	}
	return changed
}

// generateKeyPair writes a fresh ed25519 key pair in the two shapes this repo
// already stores keys in: the raw 32-byte seed loadKey reads and a PKIX PEM
// public key ParsePEMPublicKeys reads. It refuses to overwrite either file,
// because replacing a release key by accident orphans every signature made with it.
func generateKeyPair(prefix string) error {
	for _, path := range []string{prefix + ".key", prefix + ".pub"} {
		if _, err := os.Stat(path); err == nil {
			return fmt.Errorf("%s already exists; refusing to overwrite a signing key", path)
		}
	}
	pub, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		return fmt.Errorf("generating key: %w", err)
	}
	der, err := x509.MarshalPKIXPublicKey(pub)
	if err != nil {
		return fmt.Errorf("encoding public key: %w", err)
	}
	if err := os.WriteFile(prefix+".key", priv.Seed(), 0o600); err != nil {
		return fmt.Errorf("writing %s.key: %w", prefix, err)
	}
	pubPEM := pem.EncodeToMemory(&pem.Block{Type: "PUBLIC KEY", Bytes: der})
	if err := os.WriteFile(prefix+".pub", pubPEM, 0o644); err != nil {
		return fmt.Errorf("writing %s.pub: %w", prefix, err)
	}
	return nil
}

// signOneFile writes <path>.sig as base64 raw ed25519 over the file, the same
// format as a plugin tarball signature, and verifies it against trustPath when
// one is given. A missing key is reported and skipped, like the tarball path.
func signOneFile(path, keyPath, trustPath string) error {
	if keyPath == "" {
		return errors.New("-file needs -key")
	}
	key, err := loadKey(keyPath)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			fmt.Printf("pluginsigner: no signing key at %s — leaving %s unsigned\n", keyPath, path)
			return nil
		}
		return err
	}
	payload, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("reading %s: %w", path, err)
	}
	sig := base64.StdEncoding.EncodeToString(ed25519.Sign(key, payload))
	if err := os.WriteFile(path+".sig", []byte(sig), 0o644); err != nil {
		return fmt.Errorf("writing %s.sig: %w", path, err)
	}
	if trustPath != "" {
		dir, name := filepath.Split(path)
		if dir == "" {
			dir = "."
		}
		if err := verifySignatures(dir, map[string]string{name: sig}, trustPath); err != nil {
			return err
		}
	}
	fmt.Printf("pluginsigner: signed %s\n", path)
	return nil
}

// widgetEntry is the part of a widget catalog entry the manifest is built from; the
// embedded Metadata reads the same fields the host verifies.
type widgetEntry struct {
	Key     string `json:"key"`
	Version string `json:"version"`
	Bundle  string `json:"bundle"`
	widgetsig.Metadata
}

// widgetEntryFiles returns path itself, or every *.json directly inside it.
func widgetEntryFiles(path string) ([]string, error) {
	fi, err := os.Stat(path)
	if err != nil {
		return nil, err
	}
	if !fi.IsDir() {
		return []string{path}, nil
	}
	entries, err := os.ReadDir(path)
	if err != nil {
		return nil, fmt.Errorf("reading %s: %w", path, err)
	}
	var out []string
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".json") {
			out = append(out, filepath.Join(path, e.Name()))
		}
	}
	return out, nil
}

// signWidgets signs each widget entry over its widgetsig manifest and records the
// signature and bundle sha256 in the entry, verifying against trustPath when given.
// A missing key is reported and skipped, like the tarball path.
func signWidgets(path, keyPath, trustPath string) error {
	if keyPath == "" {
		return errors.New("-widget needs -key")
	}
	key, err := loadKey(keyPath)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			fmt.Printf("pluginsigner: no signing key at %s — leaving widgets unsigned\n", keyPath)
			return nil
		}
		return err
	}
	var trust []ed25519.PublicKey
	if trustPath != "" {
		if trust, err = loadTrustKeys(trustPath); err != nil {
			return err
		}
	}
	files, err := widgetEntryFiles(path)
	if err != nil {
		return err
	}
	for _, f := range files {
		if err := signWidgetEntry(f, key, trust); err != nil {
			return err
		}
	}
	fmt.Printf("pluginsigner: signed %d widget entr(ies)\n", len(files))
	return nil
}

// signWidgetEntry signs one entry file in place. The bundle path is resolved inside
// the entry's directory, exactly as the host resolves it, and may not escape it.
func signWidgetEntry(path string, key ed25519.PrivateKey, trust []ed25519.PublicKey) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("reading %s: %w", path, err)
	}
	var entry widgetEntry
	if err := json.Unmarshal(raw, &entry); err != nil {
		return fmt.Errorf("parsing %s: %w", path, err)
	}
	var doc map[string]any
	if err := json.Unmarshal(raw, &doc); err != nil {
		return fmt.Errorf("parsing %s: %w", path, err)
	}
	if entry.Key == "" || entry.Bundle == "" {
		return fmt.Errorf("%s: a widget entry needs key and bundle", path)
	}
	dir := filepath.Dir(path)
	bundlePath := filepath.Join(dir, filepath.FromSlash(entry.Bundle))
	if rel, err := filepath.Rel(dir, bundlePath); err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) || filepath.IsAbs(entry.Bundle) {
		return fmt.Errorf("%s: bundle path %q escapes the widget catalog", path, entry.Bundle)
	}
	payload, err := os.ReadFile(bundlePath)
	if err != nil {
		return fmt.Errorf("reading %s: %w", bundlePath, err)
	}
	manifest, err := widgetsig.EntryManifest(entry.Key, entry.Version, payload, entry.Metadata)
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	sig := ed25519.Sign(key, manifest)
	if trust != nil && !verifiesWithAny(trust, manifest, sig) {
		return fmt.Errorf("signature for widget %s does not verify against the trust key - the host would refuse it", entry.Key)
	}
	doc["signature"] = base64.StdEncoding.EncodeToString(sig)
	doc["sha256"] = widgetsig.BundleDigest(payload)
	out, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return fmt.Errorf("encoding %s: %w", path, err)
	}
	if err := os.WriteFile(path, append(out, '\n'), 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", path, err)
	}
	fmt.Printf("pluginsigner: signed widget %s %s\n", entry.Key, entry.Version)
	return nil
}
