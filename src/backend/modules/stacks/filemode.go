package stacks

import (
	"fmt"
	"os"
	"path/filepath"

	"gopkg.in/yaml.v3"

	"github.com/therealmcsparrow/mcharbor/core/secrets"
	"github.com/therealmcsparrow/mcharbor/internal/closeutil"
)

// resolvedComposeFile is the name of the compose file McHarbor writes beside
// the operator's own when file-based secret injection is on.
//
// The original is never edited. It is the document the operator wrote and the
// one the Compose tab shows; rewriting it in place would mean their file grew
// a volume they did not add, and a `git diff` of a GitOps-managed stack would
// never be clean again.
const resolvedComposeFile = "docker-compose.mcharbor-secrets.yml"

// writeSecretComposeFile renders a copy of the stack's compose document with
// the secret volume mounted into every service, and returns its filename
// relative to the project directory.
//
// Why every service rather than only the ones that need it: a compose file's
// environment is frequently shared through YAML anchors, `env_file` or
// interpolation, and working out which service will actually read a given
// `_FILE` variable means resolving all of that. Mounting a read-only volume of
// files a service never opens costs nothing; guessing wrong and leaving a
// service without its credential costs a failed deploy.
func writeSecretComposeFile(projectPath, composeFile, volumeName string) (string, error) {
	raw, err := os.ReadFile(filepath.Join(projectPath, composeFile))
	if err != nil {
		return "", fmt.Errorf("reading compose file: %w", err)
	}

	var doc map[string]any
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return "", fmt.Errorf("parsing compose file: %w", err)
	}
	if doc == nil {
		return "", fmt.Errorf("compose file is empty")
	}

	services, ok := doc["services"].(map[string]any)
	if !ok || len(services) == 0 {
		return "", fmt.Errorf("compose file declares no services")
	}

	mountEntry := volumeName + ":" + secrets.SecretMountPath + ":ro"
	for name, raw := range services {
		service, ok := raw.(map[string]any)
		if !ok {
			continue
		}
		service["volumes"] = appendComposeVolume(service["volumes"], mountEntry)
		services[name] = service
	}

	// Declared external: McHarbor creates and seeds the volume itself, before
	// compose runs. Letting compose create it would give an empty one, and
	// compose would then own its lifecycle — including removing it on
	// `down -v`, which would take the credentials with it mid-deploy.
	volumes, _ := doc["volumes"].(map[string]any)
	if volumes == nil {
		volumes = map[string]any{}
	}
	volumes[volumeName] = map[string]any{"external": true}
	doc["volumes"] = volumes

	out, err := yaml.Marshal(doc)
	if err != nil {
		return "", fmt.Errorf("rendering compose file: %w", err)
	}

	header := []byte("# Generated by McHarbor for file-based secret injection.\n" +
		"# Do not edit: rewritten from " + composeFile + " on every deploy.\n")
	target := filepath.Join(projectPath, resolvedComposeFile)
	if err := os.WriteFile(target, append(header, out...), 0o600); err != nil {
		return "", fmt.Errorf("writing compose file: %w", err)
	}

	return resolvedComposeFile, nil
}

// appendComposeVolume adds a mount to a service's volume list, whatever shape
// that list is currently in.
//
// Compose accepts the short string form and the long mapping form in the same
// list, and a service with no volumes at all has no key. All three appear in
// this codebase's own generated files and in operator-written ones.
func appendComposeVolume(existing any, entry string) []any {
	switch current := existing.(type) {
	case nil:
		return []any{entry}
	case []any:
		for _, item := range current {
			if text, ok := item.(string); ok && text == entry {
				// Already mounted — a redeploy must not add it twice.
				return current
			}
		}
		return append(current, entry)
	default:
		// A `volumes:` that is not a list is malformed compose; leaving it
		// alone lets compose report that rather than this function.
		return []any{entry}
	}
}

// removeSecretComposeFile deletes the generated file. Called when a stack is
// removed, and when file mode is turned off, so a stale copy cannot be picked
// up by a later deploy.
func removeSecretComposeFile(projectPath string) {
	closeutil.Remove(filepath.Join(projectPath, resolvedComposeFile))
}

// boolToInt renders a Go bool for the integer column the flag lives in.
func boolToInt(v bool) int {
	if v {
		return 1
	}
	return 0
}
