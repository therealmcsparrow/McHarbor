// Command permgen reads the McHarbor OpenAPI document and writes the
// operationId-to-permission map the CLI uses to explain a 403.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
)

type gate struct {
	Keys []string `json:"keys"`
}

type operation struct {
	OperationID string `json:"operationId"`
	Permission  []gate `json:"x-mcharbor-permission"`
}

func main() {
	spec := flag.String("spec", "", "path to openapi.json")
	out := flag.String("out", "", "output Go file")
	flag.Parse()
	if err := run(*spec, *out); err != nil {
		fmt.Fprintln(os.Stderr, "permgen:", err)
		os.Exit(1)
	}
}

func run(specPath, outPath string) error {
	raw, err := os.ReadFile(specPath)
	if err != nil {
		return fmt.Errorf("read spec: %w", err)
	}
	var doc struct {
		Info struct {
			Version string `json:"version"`
		} `json:"info"`
		Paths map[string]map[string]json.RawMessage `json:"paths"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		return fmt.Errorf("parse spec: %w", err)
	}

	keys := map[string][]string{}
	for _, item := range doc.Paths {
		for method, body := range item {
			if method == "parameters" {
				continue
			}
			var op operation
			if err := json.Unmarshal(body, &op); err != nil {
				return fmt.Errorf("parse operation: %w", err)
			}
			for _, g := range op.Permission {
				keys[op.OperationID] = append(keys[op.OperationID], g.Keys...)
			}
		}
	}

	ids := make([]string, 0, len(keys))
	for id := range keys {
		ids = append(ids, id)
	}
	sort.Strings(ids)

	var b bytes.Buffer
	b.WriteString("// Copyright (c) 2026 McSparrow. All rights reserved.\n")
	b.WriteString("// McHarbor is licensed under the McHarbor License. See LICENSE for details.\n\n")
	b.WriteString("// Code generated by tools/permgen from backend/api/openapi.json. DO NOT EDIT.\n\n")
	b.WriteString("package permissions\n\n")
	b.WriteString("// SpecVersion is the McHarbor version whose API this CLI was generated from.\n")
	fmt.Fprintf(&b, "const SpecVersion = %q\n\n", doc.Info.Version)
	b.WriteString("var byOperation = map[string][]string{\n")
	for _, id := range ids {
		fmt.Fprintf(&b, "\t%q: %#v,\n", id, keys[id])
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("format output: %w", err)
	}
	return os.WriteFile(outPath, src, 0o644)
}
