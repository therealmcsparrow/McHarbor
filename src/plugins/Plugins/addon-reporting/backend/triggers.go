// Reporting triggers.
//
// Two events the plugin itself produces are worth starting a workflow
// on: a report was generated (by hand, by a schedule, or by the
// Generate Report node), and a saved schedule finished a run, with or
// without success. Both fire through HostContext.Workflows from a
// goroutine, so the request or scheduler that produced the event never
// waits on the workflow engine.

const (
	nodeReportGeneratedTrigger   = "report-generated"
	nodeReportScheduleRanTrigger = "report-schedule-ran"

	reportFireTimeout = 15 * time.Second
)

func (p *ReportingPlugin) reportingTriggerNodes() []struct {
	key  string
	desc plugin.NodeDescriptor
} {
	typeOptions := append([]map[string]any{{"value": "any", "label": "Any"}}, reportTypeOptions()...)
	return []struct {
		key  string
		desc plugin.NodeDescriptor
	}{
		{nodeReportGeneratedTrigger, plugin.NodeDescriptor{
			Category:    "trigger",
			DisplayName: "Reporting: Report Generated",
			Description: "Starts when a report is generated. msg.payload carries the report summary.",
			Icon:        "IconChartBar",
			Inputs:      []string{},
			Outputs:     []string{"output"},
			Requires:    "reporting.read",
			Fields: []map[string]any{
				{"key": "type", "label": "Report type", "type": "select", "required": true, "default": "any", "options": typeOptions},
				{"key": "environment", "label": "Environment (empty = any)", "type": "environment-select", "required": false},
				{"key": "source", "label": "Generated by", "type": "select", "required": true, "default": "any",
					"options": []map[string]any{
						{"value": "any", "label": "Any"},
						{"value": "manual", "label": "A person (studio or API)"},
						{"value": "schedule", "label": "A schedule"},
						{"value": "workflow", "label": "A workflow node"},
					}},
				{"key": "persisted_only", "label": "Only reports saved to the library", "type": "toggle", "required": false, "default": false},
			},
		}},
		{nodeReportScheduleRanTrigger, plugin.NodeDescriptor{
			Category:    "trigger",
			DisplayName: "Reporting: Schedule Ran",
			Description: "Starts when a saved report schedule finishes a run. msg.payload carries the run outcome.",
			Icon:        "IconCalendarClock",
			Inputs:      []string{},
			Outputs:     []string{"output"},
			Requires:    "reporting.schedule",
			Fields: []map[string]any{
				{"key": "schedule", "label": "Schedule (ID or exact name; empty = any)", "type": "text", "required": false},
				{"key": "status", "label": "Outcome", "type": "select", "required": true, "default": "any",
					"options": []map[string]any{
						{"value": "any", "label": "Any"},
						{"value": "success", "label": "Succeeded"},
						{"value": "failed", "label": "Failed (generation, export or every delivery)"},
					}},
			},
		}},
	}
}

// generatedEvent is what service.Generate reports after a report
// exists. source is "manual", "schedule" or "workflow".
type generatedEvent struct {
	report    StoredReport
	source    string
	persisted bool
}

// onReportGenerated is the callback service.Generate invokes. It
// returns immediately; the firing runs in the background.
func (p *ReportingPlugin) onReportGenerated(ev generatedEvent) {
	if p.host.Workflows == nil {
		return
	}
	go func() {
		ctx, cancel := context.WithTimeout(context.Background(), reportFireTimeout)
		defer cancel()
		payload := reportSummary(ev.report)
		payload["trigger"] = nodeReportGeneratedTrigger
		payload["source"] = ev.source
		payload["persisted"] = ev.persisted
		payload["autoTriggered"] = true
		match := func(b plugin.WorkflowTriggerBinding) bool {
			if want := nodeString(b.Config, "type", "any"); want != "any" && want != ev.report.ReportType {
				return false
			}
			if want := nodeString(b.Config, "environment", ""); want != "" && want != ev.report.EnvironmentID {
				return false
			}
			if want := nodeString(b.Config, "source", "any"); want != "any" && want != ev.source {
				return false
			}
			if nodeBool(b.Config, "persisted_only", false) && !ev.persisted {
				return false
			}
			return true
		}
		started, err := p.host.Workflows.Fire(ctx, nodeReportGeneratedTrigger, payload, match)
		if err != nil {
			p.logErr("reporting: firing report-generated trigger failed", err, "report_id", ev.report.ID)
			return
		}
		if started > 0 && p.host.Logger != nil {
			p.host.Logger.Info("reporting: report-generated trigger fired", "report_id", ev.report.ID, "type", ev.report.ReportType, "runs", started)
		}
	}()
}

// onScheduleRan is the callback the scheduler invokes after a run is
// recorded, whatever its outcome.
func (p *ReportingPlugin) onScheduleRan(sc Schedule, run ScheduleRun, rec *StoredReport) {
	if p.host.Workflows == nil {
		return
	}
	go func() {
		ctx, cancel := context.WithTimeout(context.Background(), reportFireTimeout)
		defer cancel()
		outcome := "success"
		if run.Status == RunFailed {
			outcome = "failed"
		}
		deliveries := make([]map[string]any, 0, len(run.Deliveries))
		for _, d := range run.Deliveries {
			deliveries = append(deliveries, nodeJSONMap(d))
		}
		payload := map[string]any{
			"trigger":       nodeReportScheduleRanTrigger,
			"scheduleId":    sc.ID,
			"scheduleName":  sc.Name,
			"reportType":    sc.ReportType,
			"status":        run.Status,
			"outcome":       outcome,
			"code":          run.Code,
			"title":         run.Title,
			"startedAt":     run.StartedAt,
			"finishedAt":    run.FinishedAt,
			"deliveries":    deliveries,
			"autoTriggered": true,
		}
		if rec != nil {
			payload["report"] = reportSummary(*rec)
		}
		match := func(b plugin.WorkflowTriggerBinding) bool {
			if want := nodeString(b.Config, "schedule", ""); want != "" && want != sc.ID && !strings.EqualFold(want, strings.TrimSpace(sc.Name)) {
				return false
			}
			if want := nodeString(b.Config, "status", "any"); want != "any" && want != outcome {
				return false
			}
			return true
		}
		started, err := p.host.Workflows.Fire(ctx, nodeReportScheduleRanTrigger, payload, match)
		if err != nil {
			p.logErr("reporting: firing schedule-ran trigger failed", err, "schedule_id", sc.ID)
			return
		}
		if started > 0 && p.host.Logger != nil {
			p.host.Logger.Info("reporting: schedule-ran trigger fired", "schedule_id", sc.ID, "outcome", outcome, "runs", started)
		}
	}()
}

// nodeJSONMap is nodeJSON narrowed to an object, for payload lists.
func nodeJSONMap(v any) map[string]any {
	if m, ok := nodeJSON(v).(map[string]any); ok {
		return m
	}
	return map[string]any{}
}
