/**
 * The chart palette, as CSS colour strings.
 *
 * SVG needs concrete colours rather than Tailwind classes, so these are
 * the same six hues the PDF and Word exports use. They are fixed rather
 * than theme-derived on purpose: a chart a reader compares against the
 * exported PDF must be the same chart.
 */
export const chartSeriesColors = ['#276AA2', '#26B0C6', '#7C5CBE', '#C98A15', '#1E9E6A', '#A0B0BE'];

export const chartStatusColors: Partial<Record<Status, string>> = {
  good: '#1E9E6A',
  warn: '#C98A15',
  bad: '#C4483C',
  info: '#3C7DC4',
  muted: '#A0B0BE',
};

export function seriesColor(index: number, ...overrides: (Status | undefined)[]): string {
  for (const o of overrides) {
    const hit = o ? chartStatusColors[o] : undefined;
    if (hit) return hit;
  }
  return chartSeriesColors[index % chartSeriesColors.length] ?? chartSeriesColors[0] ?? '#276AA2';
}

export function bandStatus(band: Band): Status {
  switch (band) {
    case 'strong':
    case 'stable':
      return 'good';
    case 'watch':
      return 'warn';
    case 'at_risk':
    case 'critical':
      return 'bad';
    default:
      return '';
  }
}

export function severityStatus(sev: Severity): Status {
  switch (sev) {
    case 'critical':
    case 'high':
      return 'bad';
    case 'medium':
      return 'warn';
    case 'low':
      return 'info';
    default:
      return '';
  }
}

export function statusOf(s?: Status): Status {
  return s ?? '';
}
