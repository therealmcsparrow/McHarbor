import type { Band, Severity, Status } from '../types';

// Status → theme token mappings.
//
// One place decides what "warn" looks like, so a KPI tile, a table pill,
// a chart slice and a scorecard bar cannot disagree. Everything resolves
// to the host's semantic OKLCH tokens rather than raw colour, so the
// report view follows whichever theme the operator has chosen.

export const statusText: Record<Status, string> = {
  '': 'text-foreground',
  good: 'text-success',
  warn: 'text-warning',
  bad: 'text-danger',
  info: 'text-primary',
  muted: 'text-muted-foreground',
};

export const statusPill: Record<Status, string> = {
  '': 'bg-muted text-muted-foreground',
  good: 'bg-success/12 text-success',
  warn: 'bg-warning/15 text-warning',
  bad: 'bg-danger/12 text-danger',
  info: 'bg-primary/12 text-primary',
  muted: 'bg-muted text-muted-foreground',
};

export const statusAccent: Record<Status, string> = {
  '': 'bg-border',
  good: 'bg-success',
  warn: 'bg-warning',
  bad: 'bg-danger',
  info: 'bg-primary',
  muted: 'bg-muted-foreground/40',
};

/**
 * Ink for bars drawn as vectors, applied through `fill="currentColor"`.
 *
 * Deliberately `text-*` rather than the matching `fill-*` utilities: the
 * host stylesheet is generated by scanning sources, no host file uses a
 * `fill-*` utility, and a plugin frontend is only scanned when the build
 * can actually see it. `fill-success` was therefore never emitted and the
 * scorecard bars rendered with SVG's default black. Every class below is
 * one the host itself already emits, so these bars keep their status
 * colour even if the plugin sources drop out of the scan again.
 */
export const statusBarInk: Record<Status, string> = {
  '': 'text-muted-foreground',
  good: 'text-success',
  warn: 'text-warning',
  bad: 'text-danger',
  info: 'text-primary',
  muted: 'text-muted-foreground',
};

