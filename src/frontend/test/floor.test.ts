function countTests(source: string): number {
  const direct = (source.match(/\bit(\.each\([\s\S]*?\))?\(/g) ?? []).length;
  const destructive = (source.match(/\bdescribeDestructiveDialog\(\{/g) ?? []).length;
  return direct + destructive * 5;
}

describe('test floor', () => {
  it.each(Object.entries(FLOOR))('%s exists and keeps at least %i tests', (file, minimum) => {
    const path = resolve(__dirname, '..', file);
    expect(existsSync(path), `${file} is on the test floor and must not be deleted`).toBe(true);
    expect(countTests(readFileSync(path, 'utf8'))).toBeGreaterThanOrEqual(minimum);
  });
});
